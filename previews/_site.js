  // ── Search ────────────────────────────────────────────────────────────────
  // Until the index arrives (or if it can't load, e.g. from a local file
  // blocked by the browser), search falls back to page names and sections.
  let index = null;
  let loading = false;
  function loadIndex(then) {
    if (index || window.__designSearch) { index = index || window.__designSearch; then(); return; }
    if (loading) return;
    loading = true;
    const s = el('script', { src: url('_search.js') });
    s.onload = () => { index = window.__designSearch || null; then(); };
    document.head.append(s);
  }
  const fallback = () => PAGES.map(([f, t, g]) => ({ f, t, g, d: '', s: '', h: [] }));

  // NFD, not NFKD: it keeps every character's length (… stays one), so a
  // match's offsets in the folded text are its offsets in the real text.
  const norm = (s) => s.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '');
  function search(query) {
    const words = norm(query).split(/[^a-z0-9#@.-]+/).filter(Boolean);
    const pages = index || fallback();
    if (!words.length) return pages.map((p) => ({ page: p, score: 0 }));
    const all = (hay) => words.every((w) => hay.includes(w));
    const results = [];
    for (const p of pages) {
      const title = norm(p.t);
      const self = all(`${title} ${norm(GROUPS[p.g] || '')} ${norm(`${p.d} ${p.s}`)}`);
      const hits = p.h.map(([id, h, body]) => ({ id, h, body, head: all(norm(h)), any: all(norm(`${h} ${body}`)) }))
        .filter((x) => x.any)
        .sort((a, b) => b.head - a.head);
      if (self) {
        // The page itself is about the words: the page, plus any section
        // whose heading names them.
        let score = 40;
        if (all(title)) score += 60;
        if (title.startsWith(words[0])) score += 30;
        results.push({ page: p, score });
        for (const x of hits.filter((h) => h.head).slice(0, 2)) results.push({ page: p, head: x, score: score / 2 });
      } else if (hits.length) {
        // The words are in what the page says: its sections are the results.
        for (const x of hits.slice(0, 2)) results.push({ page: p, head: x, score: x.head ? 25 : 10 });
      } else if (all(`${title} ${p.h.map(([, h, body]) => norm(`${h} ${body}`)).join(' ')}`)) {
        results.push({ page: p, score: 5 }); // words spread across sections
      }
    }
    return results.sort((a, b) => b.score - a.score).slice(0, 40);
  }

  // Text with the query's words wrapped in <mark>, built as nodes.
  function marked(text, words) {
    const frag = document.createDocumentFragment();
    if (!words.length) { frag.append(text); return frag; }
    const n = norm(text);
    const spans = [];
    for (const w of words) {
      let i = n.indexOf(w);
      while (i >= 0) { spans.push([i, i + w.length]); i = n.indexOf(w, i + w.length); }
    }
    spans.sort((a, b) => a[0] - b[0]);
    let pos = 0;
    for (const [a, b] of spans) {
      if (a < pos) continue;
      frag.append(text.slice(pos, a), el('mark', { text: text.slice(a, b) }));
      pos = b;
    }
    frag.append(text.slice(pos));
    return frag;
  }
  // About 110 characters of `body` around the first word found.
  function snippet(body, words) {
    const n = norm(body);
    const first = Math.min(...words.map((w) => n.indexOf(w)).filter((i) => i >= 0));
    if (!Number.isFinite(first) || body.length <= 110) return body.slice(0, 110) + (body.length > 110 ? '…' : '');
    const from = Math.max(0, body.lastIndexOf(' ', Math.max(0, first - 30)));
    const out = body.slice(from, from + 110).trim();
    return `${from > 0 ? '…' : ''}${out}${from + 110 < body.length ? '…' : ''}`;
  }

