// search-index.mjs — the index behind the preview site's search (#209).
//
//   node scripts/search-index.mjs        (npm run search-index)
//
// Writes previews/_search.js from the pages themselves: each page's name and
// section (previews/_site.js PAGES), its one-line description (its card on
// index.html), its subtitle, and every docs section (.docs h2 and the words
// under it, code samples left out). _site.js loads the file the first time
// search opens, so pages that never search never fetch it.
//
// Generated, never edited: `npm run check` fails when it differs from what
// this script makes, so a page change that skips the rebuild is caught.
// No dependencies; the pages are hand-written and regular enough to read with
// a few patterns.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const read = (p) => readFileSync(new URL(p, root), 'utf8');

const ENTITIES = { amp: '&', lt: '<', gt: '>', quot: '"', apos: "'", nbsp: ' ', rarr: '→', larr: '←', mdash: '—', ndash: '–', hellip: '…', times: '×' };
const decode = (s) => s
  .replace(/&#x([0-9a-f]+);/gi, (_, h) => String.fromCodePoint(parseInt(h, 16)))
  .replace(/&#(\d+);/g, (_, d) => String.fromCodePoint(Number(d)))
  .replace(/&([a-z]+);/gi, (m, n) => ENTITIES[n.toLowerCase()] ?? m);
export const text = (html) => decode(html
  .replace(/<(script|style|pre|svg|template)\b[\s\S]*?<\/\1>/gi, ' ')
  .replace(/<span class="visually-hidden">[\s\S]*?<\/span>/gi, '')
  .replace(/<[^>]+>/g, ' '))
  .replace(/\s+/g, ' ')
  .trim();

// The same slug _site.js gives a docs heading that has no id of its own.
export const slug = (s) => s.toLowerCase().normalize('NFKD').replace(/[\u0300-\u036f]/g, '')
  .replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || 'section';

export function searchIndex() {
  const site = read('previews/_site.js');
  const pages = [...site.matchAll(/\['([\w-]+\.html)', '([^']+)', '(\w+)'\]/g)].map((m) => ({ file: m[1], title: m[2], group: m[3] }));
  const index = read('index.html');
  const out = [];
  for (const { file, title, group } of pages) {
    const html = read(`previews/${file}`);
    const card = index.match(new RegExp(`href="previews/${file.replace('.', '\\.')}"[\\s\\S]*?<div class="txt">([\\s\\S]*?)</div>`));
    const desc = card ? text((card[1].match(/<span>([\s\S]*?)<\/span>/) ?? ['', ''])[1]) : '';
    const sub = text((html.match(/<p class="sub">([\s\S]*?)<\/p>/) ?? ['', ''])[1]);
    const sections = [];
    const docsAt = html.search(/<div class="docs">/);
    if (docsAt >= 0) {
      const docs = html.slice(docsAt).replace(/<\/body>[\s\S]*$/, '');
      const used = new Set();
      const parts = docs.split(/<h2\b([^>]*)>([\s\S]*?)<\/h2>/);
      for (let i = 1; i < parts.length; i += 3) {
        const heading = text(parts[i + 1]);
        if (!heading) continue;
        const own = parts[i].match(/\bid="([^"]+)"/);
        let id = own ? own[1] : slug(heading);
        if (!own) { const base = id; let n = 2; while (used.has(id)) id = `${base}-${n++}`; }
        used.add(id);
        sections.push([id, heading, text(parts[i + 2] ?? '')]);
      }
    }
    out.push({ f: file, t: title, g: group, d: desc, s: sub, h: sections });
  }
  return '// Generated by scripts/search-index.mjs from the pages. Do not edit: run\n'
    + '// `npm run search-index` after changing a page, and `npm run check` checks it.\n'
    + '// Each entry: f file, t title, g section, d description, s subtitle,\n'
    + '// h docs sections as [id, heading, words].\n'
    + `window.__designSearch = ${JSON.stringify(out, null, 0).replace(/\},\{/g, '},\n{')};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(new URL('previews/_search.js', root), searchIndex());
  console.log('wrote previews/_search.js');
}
