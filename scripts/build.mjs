// build.mjs — tokens/*.json in, the CSS a consumer imports out.
//
//   node scripts/build.mjs        (npm run build)
//
// tokens/ is the source. This writes, and `npm run check` holds current:
//   tokens.css          head.css, then colour, type, space, shape, motion and
//                       component tokens, then the deprecated names, then base.css
//   tokens.chart.css    tokens/chart.json
//   tailwind.css        tokens/tailwind.json
//   tokens/names.d.ts   every token name, typed
//
// The JSON follows the W3C design-tokens shape ($value, $type, $description,
// groups), with two things it has no word for yet, kept under
// $extensions["io.brignano"]:
//   - a colour holding both schemes is { light, dark } and becomes one
//     light-dark() declaration (tokens.css rule 2);
//   - a group is one CSS rule, and names its `selector` (and `media`).
// A token's `was` is its name before 0.13; it is emitted as an alias until 1.0.
//
// No dependencies, like check.mjs: a build that needs an install stops being run.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const read = (p) => readFileSync(new URL(p, root), 'utf8');
const json = (p) => JSON.parse(read(p));
const X = 'io.brignano';
const ext = (node) => node.$extensions?.[X] ?? {};
const BANNER = (source) => `/* GENERATED by scripts/build.mjs from ${source}. Edit that, then \`npm run build\`. */\n`;

// A description as a CSS comment, continuation lines aligned under the first.
function comment(text, indent) {
  const pad = indent + '   ';
  return `${indent}/* ${text.split('\n').map((l, i) => (i && l ? pad + l : l)).join('\n')} */`;
}

const value = (t) => (typeof t.$value === 'object' ? `light-dark(${t.$value.light}, ${t.$value.dark})` : t.$value);

// Every group in a family file, as { selector, media, description, tokens }.
function groups(file) {
  const doc = json(`tokens/${file}.json`);
  return Object.entries(doc)
    .filter(([k]) => !k.startsWith('$'))
    .map(([, g]) => ({
      ...ext(g),
      description: g.$description,
      tokens: Object.entries(g).filter(([k]) => !k.startsWith('$')),
    }));
}

function rule(g) {
  const indent = g.media ? '    ' : '  ';
  const lines = [];
  g.tokens.forEach(([name, t], i) => {
    if (t.$description) lines.push((i ? '\n' : '') + comment(t.$description, indent));
    const note = ext(t).note;
    lines.push(`${indent}--${name}: ${value(t)};${note ? ` /* ${note} */` : ''}`);
  });
  const body = `${g.selector} {\n${lines.join('\n')}\n${g.media ? '  ' : ''}}`;
  return (g.description ? comment(g.description, '') + '\n' : '') + (g.media ? `@media ${g.media} {\n  ${body}\n}` : body);
}

const FAMILIES = ['color', 'type', 'space', 'shape', 'motion', 'component'];

// Names that changed in 0.13. The old one still works, pointing at the new.
function aliases() {
  const out = [];
  for (const f of FAMILIES)
    for (const g of groups(f))
      if (g.selector === ':root' && !g.media)
        for (const [name, t] of g.tokens) if (ext(t).was) out.push(`  --${ext(t).was}: var(--${name});`);
  return `/* ── Deprecated names ───────────────────────────────────────────────────
   Renamed in 0.13; removed in 1.0. Each points at its new name, so reading
   an old name still works. SETTING an old name no longer reaches the
   components, which read the new ones: set the new name instead. */\n:root {\n${out.join('\n')}\n}`;
}

function names() {
  const current = new Set(), deprecated = new Set();
  for (const f of [...FAMILIES, 'chart'])
    for (const g of groups(f))
      for (const [name, t] of g.tokens) {
        current.add(name);
        if (ext(t).was) deprecated.add(ext(t).was);
      }
  const union = (set) => [...set].sort().map((n) => `  | '--${n}'`).join('\n');
  return `// GENERATED by scripts/build.mjs from tokens/*.json. Do not edit.\n\n/** Every token @brignano/design defines. */\nexport type TokenName =\n${union(current)};\n\n/** Names from before 0.13. They still resolve; they are removed in 1.0. */\nexport type DeprecatedTokenName =\n${union(deprecated)};\n`;
}

function tailwind(known) {
  const doc = json('tokens/tailwind.json');
  const lines = [];
  for (const k of doc.keys) {
    for (const [, name] of k.value.matchAll(/var\(--([\w-]+)\)/g))
      if (!known.has(name)) throw new Error(`tokens/tailwind.json: ${k.key} points at --${name}, which no token defines`);
    if (k.comment) lines.push(comment(k.comment, '  '));
    lines.push(`  ${k.key}: ${k.value};${k.note ? ` /* ${k.note} */` : ''}`);
  }
  return `${BANNER('tokens/tailwind.json')}\n${comment(doc.$description, '')}\n\n${doc.block} {\n${lines.join('\n')}\n}\n`;
}

export function build() {
  const known = new Set();
  for (const f of [...FAMILIES, 'chart'])
    for (const g of groups(f))
      for (const [name, t] of g.tokens) {
        known.add(name);
        if (ext(t).was) known.add(ext(t).was);
      }
  // A var() that names nothing would silently compute to nothing.
  for (const f of [...FAMILIES, 'chart'])
    for (const g of groups(f))
      for (const [name, t] of g.tokens)
        for (const [, ref] of value(t).matchAll(/var\(--([\w-]+)/g))
          if (!known.has(ref)) throw new Error(`tokens/${f}.json: --${name} points at --${ref}, which no token defines`);

  const tokens = [
    BANNER('tokens/*.json (and tokens/head.css, tokens/base.css)'),
    read('tokens/head.css').trimEnd(),
    ...FAMILIES.flatMap((f) => groups(f).map(rule)),
    aliases(),
    read('tokens/base.css').trimEnd(),
  ].join('\n\n') + '\n';

  return {
    'tokens.css': tokens,
    'tokens.chart.css': BANNER('tokens/chart.json') + '\n' + groups('chart').map(rule).join('\n\n') + '\n',
    'tailwind.css': tailwind(known),
    'tokens/names.d.ts': names(),
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const [file, text] of Object.entries(build())) {
    writeFileSync(new URL(file, root), text);
    console.log('wrote', file);
  }
}
